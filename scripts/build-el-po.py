def has_greek(s: str) -> bool:
	return bool(re.search(r"[\u0370-\u03FF]", s))


def translate(msgid: str) -> str:
	if msgid in TR:
		return TR[msgid]
	if has_greek(msgid):
		return msgid
	return ""


def main() -> int:
	if not POT.exists():
		sys.stderr.write(f"Missing {POT}\n")
		return 1

	pot = polib.pofile(str(POT))
	po = polib.POFile()
	po.metadata = {
		"Project-Id-Version": "Jofme 1.7.80",
		"Report-Msgid-Bugs-To": "https://github.com/dgmaroulakos/jofme-theme",
		"POT-Creation-Date": pot.metadata.get("POT-Creation-Date", ""),
		"PO-Revision-Date": "2026-11-25 13:40+0200",
		"Last-Translator": "Jofme",
		"Language-Team": "Greek",
		"Language": "el",
		"MIME-Version": "1.0",
		"Content-Type": "text/plain; charset=UTF-8",
		"Content-Transfer-Encoding": "8bit",
		"Plural-Forms": "nplurals=2; plural=(n != 1);",
		"X-Domain": "jofme",
	}

	missing: list[str] = []
	for entry in pot:
		if not entry.msgid:
			continue
		new = polib.POEntry(
			msgid=entry.msgid,
			msgid_plural=entry.msgid_plural,
			msgctxt=entry.msgctxt,
			comment=entry.comment,
			tcomment=entry.tcomment,
			occurrences=entry.occurrences,
			flags=entry.flags,
		)
		if entry.msgid_plural:
			s0 = translate(entry.msgid)
			s1 = translate(entry.msgid_plural)
			if not s0 or not s1:
				missing.append(entry.msgid)
				missing.append(entry.msgid_plural)
			new.msgstr_plural = {0: s0 or entry.msgid, 1: s1 or entry.msgid_plural}
		else:
			s = translate(entry.msgid)
			if not s and not has_greek(entry.msgid):
				missing.append(entry.msgid)
			new.msgstr = s if s else (entry.msgid if has_greek(entry.msgid) else "")
		# Drop fuzzy from pot carry-over.
		new.flags = [f for f in new.flags if f != "fuzzy"]
		po.append(new)

	ROOT.joinpath("languages").mkdir(exist_ok=True)
	po.save(str(PO))

	# Also provide locale-only filenames WP may look for.
	(ROOT / "languages" / "el.po").write_bytes(PO.read_bytes())

	subprocess.check_call(["msgfmt", "-o", str(MO), str(PO)])
	subprocess.check_call(["msgfmt", "-o", str(ROOT / "languages" / "el.mo"), str(PO)])

	translated = sum(1 for e in po if e.translated())
	total = len(po)
	print(f"Wrote {PO.name} / {MO.name}: {translated}/{total} translated")
	if missing:
		uniq = sorted(set(missing))
		print(f"WARNING: {len(uniq)} missing English msgids:")
		for m in uniq:
			print(" -", repr(m)[:160])
		return 1
	return 0


if __name__ == "__main__":
	raise SystemExit(main())
